using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Secp256k1Net.InteropGen;

public class InteropGenerator
{
    public string GenerateNative(Secp256k1Api api)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine();

        // Collect all unique function pointer signatures and generate type aliases (inside namespace, after using System)
        var signatureToAlias = CollectFunctionPointerSignatures(api);

        sb.AppendLine("#if NET8_0_OR_GREATER");
        foreach (var kvp in signatureToAlias.OrderBy(x => x.Value))
        {
            // Use fully-qualified System.IntPtr in using aliases since they're processed before using System;
            var fullyQualifiedSignature = kvp.Key.Replace("IntPtr", "System.IntPtr");
            sb.AppendLine($"using unsafe {kvp.Value} = {fullyQualifiedSignature};");
        }
        sb.AppendLine("#endif");
        sb.AppendLine();

        sb.AppendLine("namespace Secp256k1Net");
        sb.AppendLine("{");

        // Generate function pointer type delegates that are used in public/internal APIs (available for all targets)
        // These are needed for callback marshaling - must be available for both legacy and modern targets
        var publicDelegateTypes = new HashSet<string>
        {
            "secp256k1_ecdh_hash_function",
            "secp256k1_nonce_function",
            "secp256k1_nonce_function_hardened",
            "secp256k1_ellswift_xdh_hash_function",
        };
        foreach (var fpType in api.FunctionPointerTypes.Where(f => publicDelegateTypes.Contains(f.Name)))
        {
            GenerateFunctionPointerTypeDelegate(sb, fpType);
        }

        // Generate remaining function pointer type delegates (legacy only)
        sb.AppendLine("#if !NET8_0_OR_GREATER");

        foreach (var fpType in api.FunctionPointerTypes.Where(f => !publicDelegateTypes.Contains(f.Name)))
        {
            GenerateFunctionPointerTypeDelegate(sb, fpType);
        }

        // Generate function delegates
        foreach (var func in api.Functions)
        {
            GenerateFunctionDelegate(sb, func);
        }

        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("    public unsafe partial class Secp256k1");
        sb.AppendLine("    {");

        // Generate symbol name constants
        sb.AppendLine("        // Native function symbol names");
        foreach (var func in api.Functions)
        {
            var symbolName = GetSymbolConstName(func.Name);
            sb.AppendLine($"        private const string {symbolName} = \"{func.Name}\";");
        }
        foreach (var global in api.GlobalPointers.Where(g => g.Type.StartsWith("secp256k1_") && g.Type.Contains("function")))
        {
            var symbolName = GetSymbolConstName(global.Name);
            sb.AppendLine($"        private const string {symbolName} = \"{global.Name}\";");
        }
        sb.AppendLine();

        // Modern .NET 8+ section with function pointers
        sb.AppendLine("#if NET8_0_OR_GREATER");
        GenerateModernFunctionPointers(sb, api, signatureToAlias);
        sb.AppendLine("#else");
        GenerateLegacyDelegates(sb, api);
        sb.AppendLine("#endif");

        // Generate LoadFunctions method
        sb.AppendLine();
        sb.AppendLine("        private static void LoadFunctions(IntPtr lib)");
        sb.AppendLine("        {");
        sb.AppendLine("#if NET8_0_OR_GREATER");
        GenerateModernLoadFunctions(sb, api, signatureToAlias);
        sb.AppendLine("#else");
        GenerateLegacyLoadFunctions(sb, api);
        sb.AppendLine("#endif");
        sb.AppendLine("        }");

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private void GenerateFunctionPointerTypeDelegate(StringBuilder sb, FunctionPointerType fpType)
    {
        sb.AppendLine();
        if (!string.IsNullOrEmpty(fpType.Description))
        {
            sb.AppendLine($"    /// <summary>{FormatXmlDescription(fpType.Description)}</summary>");
        }
        sb.AppendLine("    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]");

        var returnType = MapCTypeToCSharp(fpType.ReturnType);
        var hasPointerParams = fpType.Parameters.Any(p => p.Type.Contains("*"));

        sb.Append($"    public {(hasPointerParams ? "unsafe " : "")}delegate {returnType} {fpType.Name}(");

        var paramStrings = fpType.Parameters.Select(p =>
        {
            var csType = MapCTypeToCSharp(p.Type, p.Name);
            return $"{csType} {SanitizeParamName(p.Name)}";
        });

        sb.Append(string.Join(", ", paramStrings));
        sb.AppendLine(");");
    }

    private void GenerateFunctionDelegate(StringBuilder sb, FunctionDef func)
    {
        sb.AppendLine();
        if (!string.IsNullOrEmpty(func.Description))
        {
            sb.AppendLine($"    /// <summary>{FormatXmlDescription(func.Description)}</summary>");
        }

        foreach (var param in func.Parameters)
        {
            // Always generate param tags to avoid CS1573 warnings
            var description = FormatXmlDescription(param.Description);
            sb.AppendLine($"    /// <param name=\"{param.Name}\">{description}</param>");
        }

        if (!string.IsNullOrEmpty(func.ReturnDescription))
        {
            sb.AppendLine($"    /// <returns>{FormatXmlDescription(func.ReturnDescription)}</returns>");
        }

        var returnType = MapCTypeToCSharp(func.ReturnType);
        var hasPointerParams = func.Parameters.Any(p => p.Type.Contains("*"));

        // Create delegate name from function name
        var delegateName = func.Name;

        sb.Append($"    public {(hasPointerParams ? "unsafe " : "")}delegate {returnType} {delegateName}(");

        var paramStrings = func.Parameters.Select(p =>
        {
            var csType = MapCTypeToCSharp(p.Type, p.Name);
            var paramName = SanitizeParamName(p.Name);
            return $"{csType} {paramName}";
        });

        sb.Append(string.Join(", ", paramStrings));
        sb.AppendLine(");");
    }

    private Dictionary<string, string> CollectFunctionPointerSignatures(Secp256k1Api api)
    {
        var signatureToAlias = new Dictionary<string, string>();
        var aliasCounter = 0;

        // Collect signatures from all functions
        foreach (var func in api.Functions)
        {
            var signature = GetModernFunctionPointerType(func);
            if (!signatureToAlias.ContainsKey(signature))
            {
                signatureToAlias[signature] = $"FnPtr{aliasCounter++:D2}";
            }
        }

        // Collect signatures from global function pointers
        foreach (var global in api.GlobalPointers.Where(g => g.Type.StartsWith("secp256k1_") && g.Type.Contains("function")))
        {
            var signature = GetModernFunctionPointerTypeForGlobal(global, api);
            if (!signatureToAlias.ContainsKey(signature))
            {
                signatureToAlias[signature] = $"FnPtr{aliasCounter++:D2}";
            }
        }

        return signatureToAlias;
    }

    private void GenerateModernFunctionPointers(StringBuilder sb, Secp256k1Api api, Dictionary<string, string> signatureToAlias)
    {
        sb.AppendLine("        // Function pointer declarations (modern .NET 8+)");
        sb.AppendLine("#nullable disable");

        foreach (var func in api.Functions)
        {
            var fieldName = GetFieldName(func.Name);
            var funcPtrType = GetModernFunctionPointerType(func);
            var alias = signatureToAlias[funcPtrType];
            sb.AppendLine($"        private static {alias} {fieldName};");
        }

        // Global function pointer variables
        foreach (var global in api.GlobalPointers.Where(g => g.Type.StartsWith("secp256k1_") && g.Type.Contains("function")))
        {
            var fieldName = GetFieldName(global.Name);
            var funcPtrType = GetModernFunctionPointerTypeForGlobal(global, api);
            var alias = signatureToAlias[funcPtrType];
            sb.AppendLine($"        private static {alias} {fieldName};");
        }

        sb.AppendLine("#nullable restore");
    }

    private void GenerateLegacyDelegates(StringBuilder sb, Secp256k1Api api)
    {
        sb.AppendLine("        // Delegate instance fields (legacy .NET)");
        sb.AppendLine("#nullable disable");

        foreach (var func in api.Functions)
        {
            var fieldName = GetFieldName(func.Name);
            var delegateType = func.Name;
            sb.AppendLine($"        private static {delegateType} {fieldName};");
        }

        // Global function pointer variables use their typedef type
        foreach (var global in api.GlobalPointers.Where(g => g.Type.StartsWith("secp256k1_") && g.Type.Contains("function")))
        {
            var fieldName = GetFieldName(global.Name);
            sb.AppendLine($"        private static {global.Type} {fieldName};");
        }

        sb.AppendLine("#nullable restore");
    }

    private void GenerateModernLoadFunctions(StringBuilder sb, Secp256k1Api api, Dictionary<string, string> signatureToAlias)
    {
        foreach (var func in api.Functions)
        {
            var fieldName = GetFieldName(func.Name);
            var symbolName = GetSymbolConstName(func.Name);
            var funcPtrType = GetModernFunctionPointerType(func);
            var alias = signatureToAlias[funcPtrType];

            sb.AppendLine($"            {fieldName} = ({alias})NativeLibrary.GetExport(lib, {symbolName});");
        }

        // Global function pointers are data symbols - need to read the pointer
        foreach (var global in api.GlobalPointers.Where(g => g.Type.StartsWith("secp256k1_") && g.Type.Contains("function")))
        {
            var fieldName = GetFieldName(global.Name);
            var symbolName = GetSymbolConstName(global.Name);
            var funcPtrType = GetModernFunctionPointerTypeForGlobal(global, api);
            var alias = signatureToAlias[funcPtrType];

            sb.AppendLine();
            sb.AppendLine($"            // {global.Name} is a data symbol (function pointer), not a function");
            sb.AppendLine($"            var {fieldName}Ptr = NativeLibrary.GetExport(lib, {symbolName});");
            sb.AppendLine($"            {fieldName} = ({alias})Marshal.ReadIntPtr({fieldName}Ptr);");
        }
    }

    private void GenerateLegacyLoadFunctions(StringBuilder sb, Secp256k1Api api)
    {
        foreach (var func in api.Functions)
        {
            var fieldName = GetFieldName(func.Name);
            var symbolName = GetSymbolConstName(func.Name);
            var delegateType = func.Name;

            sb.AppendLine($"            {fieldName} = LoadLibNative.GetDelegate<{delegateType}>(lib, {symbolName});");
        }

        // Global function pointers are data symbols
        foreach (var global in api.GlobalPointers.Where(g => g.Type.StartsWith("secp256k1_") && g.Type.Contains("function")))
        {
            var fieldName = GetFieldName(global.Name);
            var symbolName = GetSymbolConstName(global.Name);

            sb.AppendLine();
            sb.AppendLine($"            // {global.Name} is a data symbol (function pointer), not a function");
            sb.AppendLine($"            {fieldName} = LoadLibNative.GetDelegate<{global.Type}>(lib, {symbolName}, Marshal.ReadIntPtr);");
        }
    }

    private string GetModernFunctionPointerType(FunctionDef func)
    {
        var returnType = MapCTypeToCSharpForFunctionPointer(func.ReturnType);

        var paramTypes = func.Parameters.Select(p => MapCTypeToCSharpForFunctionPointer(p.Type, p.Name)).ToList();

        if (paramTypes.Count == 0)
        {
            return $"delegate* unmanaged[Cdecl]<{returnType}>";
        }

        return $"delegate* unmanaged[Cdecl]<{string.Join(", ", paramTypes)}, {returnType}>";
    }

    private string GetModernFunctionPointerTypeForGlobal(GlobalPointer global, Secp256k1Api api)
    {
        // Find the function pointer type definition
        var fpType = api.FunctionPointerTypes.FirstOrDefault(f => f.Name == global.Type);
        if (fpType == null)
        {
            // Fallback - return a generic function pointer
            return "delegate* unmanaged[Cdecl]<int>";
        }

        var returnType = MapCTypeToCSharpForFunctionPointer(fpType.ReturnType);
        var paramTypes = fpType.Parameters.Select(p => MapCTypeToCSharpForFunctionPointer(p.Type, p.Name)).ToList();

        if (paramTypes.Count == 0)
        {
            return $"delegate* unmanaged[Cdecl]<{returnType}>";
        }

        return $"delegate* unmanaged[Cdecl]<{string.Join(", ", paramTypes)}, {returnType}>";
    }

    private string MapCTypeToCSharp(string cType, string? paramName = null)
    {
        cType = cType.Trim();

        // Handle inline function pointer types like "void (*)(const char*, void*)"
        if (cType.Contains("(*)"))
            return "IntPtr";

        // Handle specific secp256k1 types
        // Note: check for "secp256k1_context" with Contains() to handle "const secp256k1_context*"
        if (cType.Contains("secp256k1_context") && cType.Contains("*"))
            return "IntPtr";
        if (cType == "secp256k1_context")
            return "IntPtr";

        // Function pointer types as parameters
        if (cType.Contains("secp256k1_") && cType.Contains("function"))
            return "IntPtr";

        // Handle pointer types
        // Double pointers (** or "* const*" pattern) become IntPtr
        if (cType.EndsWith("**") || cType.Contains("* const*") || cType.Contains("**"))
            return "IntPtr";

        if (cType.Contains("*"))
        {

            // Most pointer types become void*
            if (cType.Contains("unsigned char") || cType.Contains("char"))
                return "void*";
            if (cType.Contains("secp256k1_"))
                return "void*";
            if (cType.Contains("void"))
                return "void*";
            if (cType.Contains("size_t"))
                return "nuint*";
            if (cType.Contains("int") && !cType.Contains("uint"))
                return "int*";

            return "void*";
        }

        // Non-pointer types
        return cType switch
        {
            "unsigned int" => "uint",
            "int" => "int",
            "size_t" => "nuint",
            "uint64_t" => "ulong",
            "int64_t" => "long",
            "uint32_t" => "uint",
            "int32_t" => "int",
            "void" => "void",
            _ => cType
        };
    }

